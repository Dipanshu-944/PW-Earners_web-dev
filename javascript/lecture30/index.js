// conditional statement

const day = "fri";
switch (day) {
  case "mon":
    console.log("1st day of week");
    break;
  case "tue":
    console.log("2st day of week");
    break;
  case "wed":
    console.log("3st day of week");
    break;
  case "thu":
    console.log("4st day of week");
    break;
  case "fri":
    console.log("5st day of week");
    break;
  case "sat":
    console.log("6st day of week");
    break;
  case "sun":
    console.log("7st day of week");
    break;
  default:
    console.log("wrong day");
}
